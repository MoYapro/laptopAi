#!/usr/bin/env bash
# Configure (first run) and start laptopai.
#
#   project-scripts/start.sh                    start; writes .env first if it doesn't exist
#   project-scripts/start.sh --reconfigure      regenerate .env (old one is kept as .env.bak)
#   project-scripts/start.sh --configure-only   only write .env, don't start anything
#
# Detected values can be overridden via environment variables, e.g.
#   GPU=cpu LLM_MODEL=gemma3:4b project-scripts/start.sh --reconfigure
set -euo pipefail

cd "$(dirname "$0")/.."

reconfigure=false
configure_only=false
for arg in "$@"; do
  case "$arg" in
    --reconfigure) reconfigure=true ;;
    --configure-only) configure_only=true ;;
    -h|--help) sed -n '2,10p' "$0"; exit 0 ;;
    *) echo "unknown option: $arg" >&2; exit 2 ;;
  esac
done

info() { printf '\033[1;34m==>\033[0m %s\n' "$*"; }
warn() { printf '\033[1;33mwarning:\033[0m %s\n' "$*" >&2; }
die()  { printf '\033[1;31merror:\033[0m %s\n' "$*" >&2; exit 1; }

command -v docker >/dev/null || die "docker is not installed"
docker compose version >/dev/null 2>&1 || die "the docker compose plugin is not installed"

# ------------------------------------------------------------------ configure

detect_gpu() {
  if command -v nvidia-smi >/dev/null && nvidia-smi -L >/dev/null 2>&1; then
    echo nvidia
  elif [[ -e /dev/kfd ]] && grep -qs 0x1002 /sys/class/drm/card*/device/vendor; then
    echo amd
  else
    echo cpu
  fi
}

detect_camera() {
  # First V4L2 node that can capture video (webcams often expose a second metadata-only node).
  local dev
  for dev in /dev/video*; do
    [[ -e "$dev" ]] || continue
    if command -v v4l2-ctl >/dev/null; then
      v4l2-ctl -d "$dev" --all 2>/dev/null | grep -q 'Video Capture' && { echo "$dev"; return; }
    else
      echo "$dev"; return
    fi
  done
  echo /dev/video0
}

write_env() {
  local gpu=${GPU:-$(detect_gpu)}
  local compose_file
  case "$gpu" in
    nvidia) compose_file=compose.yaml:compose.nvidia.yaml ;;
    amd)    compose_file=compose.yaml:compose.amd.yaml ;;
    cpu)    compose_file=compose.yaml ;;
    *) die "GPU must be nvidia, amd or cpu (got '$gpu')" ;;
  esac

  local video_gid camera
  video_gid=$(getent group video | cut -d: -f3 || true)
  camera=${CAMERA_DEVICE:-$(detect_camera)}
  [[ -e "$camera" ]] || warn "camera $camera not found; the app will run without vision"

  if [[ -f .env ]]; then
    cp .env .env.bak
    info "previous .env saved as .env.bak"
  fi

  cat > .env <<EOF
# Generated by project-scripts/start.sh on $(date -Iseconds) for $(hostname) (gpu: $gpu).
# Edit freely; regenerate with: project-scripts/start.sh --reconfigure

# --- which compose files / services to use
COMPOSE_FILE=$compose_file
COMPOSE_PROFILES=llm
OLLAMA_URL=http://llm:11434
# To use an Ollama running elsewhere instead, remove COMPOSE_PROFILES and set:
# OLLAMA_URL=http://host.docker.internal:11434

# --- host ids
UID=$(id -u)
GID=$(id -g)
VIDEO_GID=${video_gid:-44}
CAMERA_DEVICE=$camera

# --- models (keep the LLM under ~3 GB so it fits the laptop's 4 GB VRAM)
LLM_MODEL=${LLM_MODEL:-qwen3.5:4b}
LLM_THINK=${LLM_THINK:-false}
# background memory review: first available model is used; 0 GPU layers keeps it on CPU/RAM
MEMORY_MODEL=${MEMORY_MODEL:-qwen3.5-9b-uncensored,qwen3.5:9b}
MEMORY_NUM_GPU=${MEMORY_NUM_GPU:-$([[ $gpu == nvidia ]] && echo 0 || echo -1)}
WHISPER_MODEL=${WHISPER_MODEL:-small}
WHISPER_LANGUAGE=${WHISPER_LANGUAGE:-}
PIPER_VOICE=${PIPER_VOICE:-en_US-amy-medium}
PIPER_SPEED=${PIPER_SPEED:-1.1}
PIPER_VARIATION=${PIPER_VARIATION:-1.25}
APP_PORT=${APP_PORT:-8080}
EOF

  info "wrote .env: gpu=$gpu, camera=$camera, video gid=${video_gid:-44}, model=${LLM_MODEL:-qwen3.5:4b}"
}

if [[ ! -f .env ]] || $reconfigure; then
  write_env
else
  info "using existing .env (regenerate with --reconfigure)"
fi
$configure_only && exit 0

mkdir -p data

# ------------------------------------------------------------------ preflight

config_services=$(docker compose config --services)
run_llm=false
grep -qx llm <<<"$config_services" && run_llm=true

if $run_llm; then
  if docker ps --format '{{.Names}}' | grep -qx ollama; then
    die "a standalone 'ollama' container is running (same port and GPU). Stop it first: docker stop ollama"
  fi
  if docker compose config | grep -q 'driver: nvidia' && ! docker info 2>/dev/null | grep -qi nvidia; then
    die "NVIDIA GPU configured, but Docker has no NVIDIA runtime. Install nvidia-container-toolkit, then: sudo nvidia-ctk runtime configure --runtime=docker && sudo systemctl restart docker"
  fi
fi

# Resolved model name (respects .env and environment overrides).
model=$(docker compose config | awk '$1 == "LLM_MODEL:" { gsub(/"/, "", $2); print $2; exit }')

# ------------------------------------------------------------------ start

if $run_llm; then
  info "starting Ollama"
  docker compose up -d llm
  for _ in $(seq 60); do
    docker compose exec -T llm ollama list >/dev/null 2>&1 && break
    sleep 1
  done
  docker compose exec -T llm ollama list >/dev/null 2>&1 || die "Ollama did not come up; see: docker compose logs llm"

  if ! docker compose exec -T llm ollama show "$model" >/dev/null 2>&1; then
    info "pulling $model (first run only)"
    docker compose exec -T llm ollama pull "$model"
  fi

  # Memory model: a preference list; if none of them is available, pull the last (a registry model).
  memory_models=$(docker compose config | awk '$1 == "MEMORY_MODEL:" { gsub(/"/, "", $2); print $2; exit }')
  have_memory_model=false
  IFS=',' read -ra candidates <<<"$memory_models"
  for m in "${candidates[@]}"; do
    docker compose exec -T llm ollama show "$m" >/dev/null 2>&1 && { have_memory_model=true; break; }
  done
  if ! $have_memory_model && [[ ${#candidates[@]} -gt 0 ]]; then
    info "pulling memory model ${candidates[-1]} (first run only)"
    docker compose exec -T llm ollama pull "${candidates[-1]}"
  fi
else
  info "no llm service enabled; using external Ollama (OLLAMA_URL in .env)"
fi

info "building and starting the app"
docker compose up -d --build app

port=$(docker compose port app 8080 | awk -F: '{ print $NF }')
url="http://localhost:${port:-8080}"
for _ in $(seq 60); do
  status=$(curl -fsS "$url/api/status" 2>/dev/null) && break
  sleep 1
done
[[ -n "${status:-}" ]] || die "app did not respond at $url; see: docker compose logs app"

info "status: $status"
info "ready: $url   (models finish warming up in the background on first start)"
